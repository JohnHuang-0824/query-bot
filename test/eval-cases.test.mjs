/**
 * 評測集本身的檢查 —— 不連模型。
 *
 * 作答題的 must_contain 只比對字面：結論是「可以」的題目，「不可以」也命中；
 * 結論是「不能」的題目，答「可以」只要別處提到「不能」也會通過。擋相反結論靠
 * must_not_conclude 的正規表達式，這裡驗它們：擋得住相反結論、又不會誤擋 gold
 * 與正確的說法。
 *
 * ⚠️ 改了這幾題的 must_not_conclude 就要跑這個。評測跑出誤擋或漏擋時，
 *    把那句實際回答加進下面的樣本。
 */

